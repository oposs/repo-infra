"""apply --item changelog-fragments (D40): the switch from [Unreleased] to
fragment files, on fixture repositories."""

import datetime
import json
import pathlib
import shutil
import subprocess

import pytest
from piecekit import make_assets

from repo_infra import check, cli, fragments
from repo_infra.apply import BRANCH, ApplyError

ROOT = pathlib.Path(__file__).resolve().parents[1]
NOW = datetime.datetime(2026, 11, 26, 9, 21, tzinfo=datetime.UTC)
NOTE = ("Changelog fragments: `CHANGES.d/`. Pull requests do not edit this file. Each\n"
        "pull request adds its entry as a file in `CHANGES.d/new/`,\n"
        "`CHANGES.d/changed/` or `CHANGES.d/fixed/`. The release pull request moves\n"
        "the entries into this file.\n")
HEADER = "# Changelog\n\nAll notable changes to this project are listed here.\n\n"
RELEASED = "## 1.0.0 - 2026-01-01\n\n### New\n\n- The first release.\n"
SKELETON = "## [Unreleased]\n\n### New\n\n### Changed\n\n### Fixed\n\n"
FILLED = ("## [Unreleased]\n\n### New\n\n- A `--quiet` option.\n- A `--loud` option that\n"
          "  prints every step.\n\n### Changed\n\n### Fixed\n\n- The crash on an empty file. (#7)\n\n")


def rands(*values):
    it = iter(values)
    return lambda: next(it)


def write_changes(root, text):
    root.mkdir(parents=True, exist_ok=True)
    (root / "CHANGES.md").write_bytes(text.encode("utf-8"))


def read(root, path):
    return (root / path).read_bytes().decode("utf-8")


def node_roll(tmp_path, before, after, fragment_list):
    """The released section and everything below it, as the classic roll of
    `before` and the fragment roll of `after` write them."""
    node = shutil.which("node")
    if node is None:
        pytest.skip("node is not installed")
    script = tmp_path / "roll.js"
    script.write_text(
        "const changes = require(%s);\n"
        "const input = JSON.parse(require('fs').readFileSync(0, 'utf8'));\n"
        "const tail = (t) => t.slice(t.indexOf('## 1.1.0 - 2026-11-27'));\n"
        "console.log(JSON.stringify({\n"
        "  classic: tail(changes.roll(input.before, '1.1.0', '2026-11-27')),\n"
        "  fragments: tail(changes.roll(input.after, '1.1.0', '2026-11-27', input.list)),\n"
        "}));\n" % json.dumps(str(ROOT / ".github/workflows/lib/changes.js")),
        encoding="utf-8")
    proc = subprocess.run([node, str(script)], capture_output=True, text=True,
                          input=json.dumps({"before": before, "after": after,
                                            "list": fragment_list}))
    assert proc.returncode == 0, proc.stderr
    return json.loads(proc.stdout)


def test_a_skeleton_only_unreleased_gets_the_note_and_the_readme_and_no_fragment(tmp_path):
    write_changes(tmp_path, HEADER + SKELETON + RELEASED)
    paths = fragments.switch_to_fragments(tmp_path, NOW, rands())
    assert paths == ["CHANGES.md", "CHANGES.d/README.md"]
    assert read(tmp_path, "CHANGES.md") == HEADER + NOTE + "\n" + RELEASED
    assert not any(p.is_dir() for p in (tmp_path / "CHANGES.d").iterdir())
    readme = read(tmp_path, "CHANGES.d/README.md")
    for said in ("new/", "changed/", "fixed/", "UTC", "4 random hex",
                 "date -u +%Y%m%d-%H%M", "openssl rand -hex 2"):
        assert said in readme
    # check reads the result as a finished switch.
    assert [(i.name, i.state, i.detail) for i in check.changelog_items(tmp_path)] == [
        ("changelog-mode", "ok", "fragments in CHANGES.d/")]


def test_filled_new_and_fixed_become_two_fragments_that_roll_as_the_classic_roll(tmp_path):
    before = HEADER + FILLED + RELEASED
    write_changes(tmp_path, before)
    paths = fragments.switch_to_fragments(tmp_path, NOW, rands("a3f9", "0b1c"))
    new = "CHANGES.d/new/20261126-0921-a3f9-unreleased.md"
    fixed = "CHANGES.d/fixed/20261126-0921-0b1c-unreleased.md"
    assert paths == ["CHANGES.md", "CHANGES.d/README.md", new, fixed]
    assert read(tmp_path, new) == ("- A `--quiet` option.\n- A `--loud` option that\n"
                                   "  prints every step.\n")
    assert read(tmp_path, fixed) == "- The crash on an empty file. (#7)\n"
    assert not (tmp_path / "CHANGES.d/changed").exists()
    after = read(tmp_path, "CHANGES.md")
    assert after == HEADER + NOTE + "\n" + RELEASED
    listed = [{"section": p.split("/")[1], "name": p.split("/")[2], "text": read(tmp_path, p)}
              for p in (new, fixed)]
    rolled = node_roll(tmp_path, before, after, listed)
    assert rolled["fragments"] == rolled["classic"]


def test_a_crlf_changes_md_keeps_its_line_ends(tmp_path):
    before = (HEADER + FILLED + RELEASED).replace("\n", "\r\n")
    write_changes(tmp_path, before)
    fragments.switch_to_fragments(tmp_path, NOW, rands("a3f9", "0b1c"))
    assert read(tmp_path, "CHANGES.md") == (HEADER + NOTE + "\n" + RELEASED).replace("\n", "\r\n")
    assert read(tmp_path, "CHANGES.d/fixed/20261126-0921-0b1c-unreleased.md") == (
        "- The crash on an empty file. (#7)\n")


def test_entries_the_fragment_rules_cannot_hold_are_refused_and_each_is_named(tmp_path):
    before = (HEADER + "## [Unreleased]\n\nA line before any subsection.\n\n### New\n\n"
              "- A feature.\n  #### Details\n\n### Removed\n\n- The `--old` option.\n\n"
              "### Fixed\n\nThe crash on start.\n\n" + RELEASED)
    write_changes(tmp_path, before)
    with pytest.raises(ApplyError) as refusal:
        fragments.switch_to_fragments(tmp_path, NOW, rands("a3f9", "0b1c"))
    message = str(refusal.value)
    for said in ("A line before any subsection.", "- A feature.", "#### Details",
                 "### Removed", "- The `--old` option.", "The crash on start."):
        assert said in message
    assert read(tmp_path, "CHANGES.md") == before
    assert not (tmp_path / "CHANGES.d").exists()


def test_a_second_run_is_refused(tmp_path):
    write_changes(tmp_path, HEADER + FILLED + RELEASED)
    fragments.switch_to_fragments(tmp_path, NOW, rands("a3f9", "0b1c"))
    with pytest.raises(ApplyError, match="already uses fragments in CHANGES.d/"):
        fragments.switch_to_fragments(tmp_path, NOW, rands("1111", "2222"))


def git(root, *args):
    return subprocess.run(["git", *args], cwd=root, check=True, capture_output=True,
                          text=True).stdout


@pytest.fixture
def repo(tmp_path):
    root = tmp_path / "repo"
    write_changes(root, HEADER + FILLED + RELEASED)
    git(root, "init", "-q", "-b", "main")
    git(root, "add", ".")
    git(root, "commit", "-qm", "start")
    return root


def run_apply(monkeypatch, tmp_path, repo, *extra):
    monkeypatch.setattr(cli, "ASSETS", make_assets(tmp_path / "assets", {}))
    monkeypatch.setattr(cli, "read_facts", lambda repo_name: cli.CONFORMING_FACTS)
    return cli.run(["apply", "--root", str(repo), "--repo", "o/r", *extra])


def test_apply_item_switches_on_the_branch_in_one_commit(monkeypatch, tmp_path, repo):
    assert run_apply(monkeypatch, tmp_path, repo, "--item", "changelog-fragments") == 0
    assert git(repo, "rev-parse", "--abbrev-ref", "HEAD").strip() == BRANCH
    assert git(repo, "log", "-1", "--format=%s").strip() == (
        "Switch the changelog to fragments (D40)")
    assert git(repo, "status", "--porcelain") == ""
    shown = git(repo, "show", "--name-only", "--format=").split()
    assert sorted(shown) == sorted(["CHANGES.md", "CHANGES.d/README.md",
                                    *(str(p.relative_to(repo).as_posix()) for p in
                                      (repo / "CHANGES.d").glob("*/*.md"))])
    assert fragments.note_dir(read(repo, "CHANGES.md")) == "CHANGES.d"


def test_a_bare_apply_never_switches(monkeypatch, tmp_path, repo):
    assert run_apply(monkeypatch, tmp_path, repo) == 0
    assert read(repo, "CHANGES.md") == HEADER + FILLED + RELEASED
    assert not (repo / "CHANGES.d").exists()


def test_apply_item_refuses_a_merged_file(monkeypatch, tmp_path, repo):
    with pytest.raises(ApplyError, match="--from"):
        run_apply(monkeypatch, tmp_path, repo, "--item", "changelog-fragments",
                  "--from", "x.md")
