"""Changelog fragments (D40): the rules, and the switch apply makes.

The JS in .github/workflows/lib/fragments.js enforces the same rules when a pull
request is judged and a release rolled; change both. tests/fixtures/
changelog-fragments/cases.json holds the cases both sides must agree on.
"""

import datetime
import pathlib
import posixpath
import re

SECTIONS = ("new", "changed", "fixed")
NOTE_RE = re.compile(r"^Changelog fragments: `([^`]+?)/?`")
NAME_RE = re.compile(r"^[0-9]{8}-[0-9]{4}-[0-9a-f]{4}-[a-z0-9]+(-[a-z0-9]+)*\.md$")
_NEWLINE = re.compile(r"\r?\n")


def lines_of(text):
    return _NEWLINE.split(text)


def header_end(lines):
    """Index of the first '## ' line; a note below it belongs to a release entry."""
    return next((i for i, line in enumerate(lines) if line.startswith("## ")), len(lines))


def _refused_dir(raw, directory):
    if raw.startswith("/"):
        return "is absolute"
    if ".." in raw.split("/"):
        return "contains '..'"
    if directory == ".":
        return "is the repository root"
    if directory == ".github" or directory.startswith(".github/"):
        return "is or lies under '.github'"
    if directory == "CHANGES.md":
        return "is 'CHANGES.md'"
    return None


def note_dir(text):
    """The directory the note in the header of CHANGES.md names, or None.

    Normalised, so './CHANGES.d/' and 'CHANGES.d//' read as 'CHANGES.d', the way
    GitHub names the files. Raises ValueError for a directory the rules refuse.
    """
    lines = lines_of(text)
    for line in lines[:header_end(lines)]:
        match = NOTE_RE.match(line)
        if not match:
            continue
        raw = match.group(1)
        directory = posixpath.normpath(raw)
        reason = _refused_dir(raw, directory)
        if reason:
            raise ValueError(f"Changelog fragments directory '{raw}' {reason}")
        return directory
    return None


def classify_path(directory, path):
    """('outside' | 'root' | 'fragment' | 'refused', detail) for a path in the repository."""
    if not path.startswith(f"{directory}/"):
        return ("outside", None)
    parts = path[len(directory) + 1:].split("/")
    if len(parts) == 1:
        return ("root", None)
    if parts[0] not in SECTIONS:
        return ("refused", f"'{parts[0]}' is not one of new, changed, fixed")
    if len(parts) > 2:
        return ("refused", f"'{path}' is in a subdirectory of {directory}/{parts[0]}/")
    if not NAME_RE.match(parts[1]):
        return ("refused",
                f"'{parts[1]}' does not match <yyyymmdd>-<hhmm>-<4 hex>-<topic>.md")
    return ("fragment", parts[0])


def _parse(text):
    """(problem, entries): entries are '- ' lines plus two-space continuation lines."""
    out = []
    for line in lines_of(text):
        if line.strip() == "":
            continue
        if line.startswith("- "):
            if line[2:].strip() == "":
                return (f"an entry without text: '{line}'", [])
            out.append([line])
        elif line.startswith("  ") and out:
            out[-1].append(line)
        elif line.startswith("#"):
            return (f"a line starts with '#': {line}", [])
        else:
            return (f"text outside an entry: {line}", [])
    if not out:
        return ('no entry (a line starting with "- ")', [])
    return (None, ["\n".join(entry) for entry in out])


def fragment_problem(text):
    return _parse(text)[0]


def entries(text):
    return _parse(text)[1]


# --- The switch from [Unreleased] to fragments (apply --item changelog-fragments)

DIRECTORY = "CHANGES.d"
UNRELEASED = "## [Unreleased]"
HEADINGS = {f"### {s.capitalize()}": s for s in SECTIONS}
NOTE = (
    "Changelog fragments: `CHANGES.d/`. Pull requests do not edit this file. Each",
    "pull request adds its entry as a file in `CHANGES.d/new/`,",
    "`CHANGES.d/changed/` or `CHANGES.d/fixed/`. The release pull request moves",
    "the entries into this file.",
)
README = """# Changelog fragments

Each pull request adds its changelog entry as a file in `new/`, `changed/` or
`fixed/`. The release pull request moves the entries into `CHANGES.md`, under
`### New`, `### Changed` and `### Fixed`, and deletes the files.

A file holds one or more entries. An entry is a line that starts with `- `,
followed by lines indented by two spaces. A heading or any other text is
refused.

A file name is the UTC time to the minute, 4 random hex characters and a
topic, for example `new/20261126-0921-a3f9-time-band.md`. These commands print
the first two parts:

```sh
date -u +%Y%m%d-%H%M
openssl rand -hex 2
```

Within a section, the entries are released in the order of the file names,
so the oldest file comes first.
"""


def _unreleased_problems(block):
    """(problems, {section: [entry lines]}) for the lines of the [Unreleased] block.

    Read as the classic roll reads it: a '### ' line opens a subsection, and
    the same heading twice (two branches each brought a skeleton) is one.
    Every problem names the entry or line, so whoever rewrites CHANGES.md
    finds each one.
    """
    problems, found = [], {}
    heading, entry = None, None
    for line in block:
        # Only an unindented '### ' opens a subsection; an indented one is a
        # heading inside an entry and is refused below, never dropped.
        if line.startswith("### "):
            heading, entry = line.strip(), None
            continue
        if line.strip() == "":
            continue
        if heading is None:
            problems.append(f"text before the first subsection: {line}")
        elif heading not in HEADINGS:
            # Reached only for a non-blank line, so an empty unknown subsection
            # (a skeleton's '### Removed') is dropped: it holds no entry.
            problems.append(f"{heading} is not New, Changed or Fixed: {line}")
        elif line.rstrip() == "-":
            problems.append(f"{heading} has an empty list item: {line}")
        elif line.startswith("- ") and line[2:].strip():
            entry = [line]
            found.setdefault(HEADINGS[heading], []).append(entry)
        elif line.lstrip().startswith("#"):
            where = f"entry '{entry[0]}'" if entry else "subsection"
            problems.append(f"{heading} {where} holds a heading: {line}")
        elif line.startswith("  ") and entry is not None:
            entry.append(line)
        else:
            problems.append(f"{heading} has text outside a list item: {line}")
    return problems, found


def switch_to_fragments(repo_root, now, rand):
    """Move the entries of [Unreleased] into fragments and write the note (D40).

    One fragment per subsection that has entries, in their old order; the
    README of the directory; CHANGES.md without [Unreleased] and with the
    note as the last paragraph of the header. Returns the paths it wrote.
    An entry the fragment rules cannot hold is refused, never rewritten:
    rewording a changelog entry is a judgement over prose.
    """
    # apply imports check, which imports this module.
    from .apply import ApplyError

    root = pathlib.Path(repo_root)
    changes = root / "CHANGES.md"
    if not changes.is_file():
        raise ApplyError("there is no CHANGES.md to switch to fragments")
    text = changes.read_bytes().decode("utf-8")
    try:
        directory = note_dir(text)
    except ValueError as error:
        raise ApplyError(str(error)) from None
    if directory is not None:
        raise ApplyError(f"CHANGES.md already uses fragments in {directory}/")
    if (root / DIRECTORY).exists():
        raise ApplyError(f"{DIRECTORY}/ already exists; CHANGES.md has no note naming it, "
                         "so move it away or add the note by hand")
    lines = lines_of(text)
    start = next((i for i, line in enumerate(lines) if line.strip() == UNRELEASED), None)
    if start is None:
        raise ApplyError(f"CHANGES.md has no '{UNRELEASED}' heading to move into fragments")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")),
               len(lines))
    problems, found = _unreleased_problems(lines[start + 1:end])
    if problems:
        raise ApplyError("CHANGES.md has entries in [Unreleased] that a fragment cannot "
                         "hold; rewrite them as '- ' entries under New, Changed or Fixed "
                         "and run again:\n" + "\n".join(f"  {p}" for p in problems))

    if now.tzinfo is not None:
        now = now.astimezone(datetime.UTC)
    stamp = now.strftime("%Y%m%d-%H%M")
    texts = {}
    for section in SECTIONS:
        if section not in found:
            continue
        name = f"{stamp}-{rand()}-unreleased.md"
        if not NAME_RE.match(name):
            raise ApplyError(f"{name}: not a fragment name")
        texts[f"{DIRECTORY}/{section}/{name}"] = "".join(
            "\n".join(entry) + "\n" for entry in found[section])

    rest = lines[:start] + lines[end:]
    at = header_end(rest)
    header = rest[:at]
    while header and header[-1].strip() == "":
        header.pop()
    head = header + [""] if header else []
    out = head + list(NOTE) + [""] + rest[at:]
    eol = "\r\n" if "\r\n" in text else "\n"
    # A file whose last line is the note still ends with a line end.
    result = eol.join(out) if rest[at:] else eol.join(out[:-1]) + eol

    changes.write_bytes(result.encode("utf-8"))
    written = ["CHANGES.md", f"{DIRECTORY}/README.md"]
    (root / DIRECTORY).mkdir()
    (root / DIRECTORY / "README.md").write_text(README, encoding="utf-8")
    for path, body in texts.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(body, encoding="utf-8")
        written.append(path)
    return written
